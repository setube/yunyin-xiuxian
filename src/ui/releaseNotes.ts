/**
 * 发布说明数据 —— 游戏内「版本与更新」的文本与口吻规范。
 *
 * ## 风格规范(写每一条热更前先读)
 *
 * 本作采用「天道热更新」的文言修仙口吻,由三条铁律约束:
 *
 *  一、**真事为纲**:intro / closing 可以与事实对不上,但 `changes` 的每一条都必须
 *      来自 CHANGELOG 对应版本的实改项 —— 不许给玩家写它没拿到的东西。
 *  二、**以时、数为浆**:热更的卖点落在「知时限、溯来路」这类可感知之事上,
 *      不写空泛的「性能优化」四个字。写「以现下修速为度,报『约 X 后』」,
 *      不写「优化了等待体验」。
 *  三、**排版三件套**:intro 承前(「鸿蒙初判…」),changes 用「一、二、三…」逐条点账,
 *      closing 收尾(「自此而后…」)+「谶曰:…」+ 落款「——天道有司 谨告」。
 *
 * 本文件保持零依赖(不 import 任何东西),以便测试只喂数据、不被随机引入的
 * 依赖链拖住;同时它也是发布说明的单点 —— 加一条新版本,改这里即可。
 *
 * ## 与 CHANGELOG 的关系(重要)
 * 只有「玩家可感的已发布版本」才加一条:首条的 version 必须 == package.json 的
 * version(releaseNotes.spec.ts 钉死,否则「已是最新 / 新版本就绪」会自相矛盾)。
 * CHANGELOG 里纯内部的版本(如 1.37.1 / 1.37.2 的模拟器校准、数据层韧性修复,
 * 无任何玩家可见内容,且 package.json 未抬版本)刻意不在这儿落条 —— 别给玩家
 * 编它没拿到的东西。加新版本时:实改点逐条取自 CHANGELOG,不外推、不编造。
 */

export interface ReleaseNote {
  /** 版本号;首条必须与 package.json 的 version 对上(见上文「与 CHANGELOG 的关系」) */
  version: string
  /** 发布日期,YYYY-MM-DD */
  date: string
  /** 热更题名(如「天道热更新·…」) */
  title: string
  /** 开篇散文,按空行节奏排(数组每项一段) */
  intro: string[]
  /** 实改点,逐条「一、二、三…」 */
  changes: string[]
  /** 收尾散文(可含「谶曰」),可省略 */
  closing?: string[]
  /** 落款序号(如「——天道有司 谨告」),可省略 */
  sign?: string
}

