export const SAVE_FILE_TEXT = {
  /** 选中的文件是空的 */
  empty: '文件为空',
  /** 读不出(编码坏、权限、解析失败) */
  unreadable: '文件无法读取',
  /** 超过读入上限,当场回执而不是读进内存 */
  tooLarge: '文件过大',
  /** 导入成功 */
  importOk: '导入成功',
  /** 导出失败(原生桥无回执 / 抛异常) */
  exportFailed: '导出失败'
} as const
