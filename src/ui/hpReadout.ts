/**
 * 血条读数。
 *
 * 历练的战斗面板与天劫的连战面板各有一对血条,原先都只画比例、不标数字:
 * 战报逐回合报「53.1亿」这种伤害,而最该报的「还剩几成」反而没有 ——
 * 玩家得自己拿条长去估,战报与条成了两套读法。
 *
 * 这一层只做一件事:把 0~1 的比例翻成读数。
 * 两处界面共用同一把尺,改口径时只改这一处,不会一处写 0% 另一处写 0.4%。
 */

/**
 * 比例 → 百分数读数。
 *
 * 三个边界刻意硬写,不走四舍五入:
 *   - 归零写 0%:0.4% 若被抹成 0 还是 1 都无所谓,但「已归零」与「还剩一丝」在战斗里是两件事;
 *   - 满血写 100%:99.6% 同理,「满」与「差一点」也是两件事;
 *   - 非有限值给「—」:坏档不静默画成满血。
 *
 * @param v 0~1 的比例
 */
export function hpPercent(v: number): string {
  if (!Number.isFinite(v)) return '—'
  const pct = Math.max(0, Math.min(100, v * 100))
  if (pct <= 0) return '0%'
  if (pct >= 100) return '100%'
  return `${Math.round(pct)}%`
}
